//! of 8 bits, MSB = leftmost pixel. Based on the classic IBM CGA/BIOS 8x8
//! font (public domain).
//!
//! Copied from `crates/oasis-backend-psp/src/font.rs` (bitmap data only,
//! no system font dependency).

