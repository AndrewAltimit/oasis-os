//! Built-in skin definitions.
//!
//! Each skin is defined as embedded TOML constants. These provide functional
//! skins out of the box without requiring external skin directories.
//!
//! Skins are organized into three category modules:
//! - `classic` -- classic/retro skins (terminal, tactical, classic, retro-cga, win95)
//! - `modern` -- modern/desktop skins (desktop, modern, xp, macos, gnome, agent-terminal)
//! - `special` -- special/stylized skins (corrupted, cyberpunk, paper, solarized,
//!   vaporwave, highcontrast, altimit)
//!
//! Additionally, `generated` contains build-time generated loaders from TOML
//! directories in `skins/`. These are auto-generated by `build.rs` and produce
//! identical skins to the handwritten versions for the 12 TOML-based skins.

mod classic;
mod modern;
mod special;

/// Build-time generated skin loaders from `skins/` TOML directories.
pub mod generated {
    include!(concat!(env!("OUT_DIR"), "/builtin_generated.rs"));
}

pub use classic::{classic_skin, retro_cga_skin, tactical_skin, terminal_skin, win95_skin};
pub use modern::{agent_terminal_skin, desktop_skin, gnome_skin, macos_skin, modern_skin, xp_skin};
pub use special::{
    altimit_skin, corrupted_skin, cyberpunk_skin, highcontrast_skin, paper_skin, protanopia_skin,
    solarized_skin, tritanopia_skin, vaporwave_skin,
};

use oasis_types::error::Result;

use super::loader::Skin;

/// Load a built-in skin by name with optional inheritance.
///
/// If the skin's manifest specifies `inherits = "parent_name"`, the parent
/// skin is loaded first and its theme/layout fields fill in any missing
/// values in the child. Max inheritance depth is 3.
pub fn load_builtin(name: &str) -> Result<Skin> {
    load_builtin_recursive(name, 0)
}

fn load_builtin_raw(name: &str) -> Result<Skin> {
    match name {
        "classic" => classic_skin(),
        "terminal" => terminal_skin(),
        "tactical" => tactical_skin(),
        "corrupted" => corrupted_skin(),
        "desktop" => desktop_skin(),
        "agent-terminal" => agent_terminal_skin(),
        "modern" => modern_skin(),
        "xp" => xp_skin(),
        "macos" => macos_skin(),
        "gnome" => gnome_skin(),
        "retro-cga" => retro_cga_skin(),
        "cyberpunk" => cyberpunk_skin(),
        "paper" => paper_skin(),
        "win95" => win95_skin(),
        "solarized" => solarized_skin(),
        "vaporwave" => vaporwave_skin(),
        "highcontrast" => highcontrast_skin(),
        "altimit" => altimit_skin(),
        "protanopia" => protanopia_skin(),
        "tritanopia" => tritanopia_skin(),
        _ => Err(oasis_types::error::OasisError::Config(
            format!("unknown built-in skin: {name}").into(),
        )),
    }
}

fn load_builtin_recursive(name: &str, depth: u32) -> Result<Skin> {
    const MAX_DEPTH: u32 = 3;
    if depth > MAX_DEPTH {
        return Err(oasis_types::error::OasisError::Config(
            format!("skin inheritance depth exceeds {MAX_DEPTH} for '{name}'").into(),
        ));
    }

    let mut skin = load_builtin_raw(name)?;

    if let Some(ref parent_name) = skin.manifest.inherits {
        let parent = load_builtin_recursive(parent_name, depth + 1)?;
        skin.merge_theme_from(&parent);
    }

    Ok(skin)
}

