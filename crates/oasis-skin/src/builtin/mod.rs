    #[test]
    fn generated_skins_match_handwritten_manifest() {
        // Compare generated skins against handwritten versions for the 12
        // TOML-based skins. Only compare fields that should be identical
        // (the TOML files are the source of truth for both).
        let toml_skins: &[&str] = &[
            "classic",
            "retro-cga",
            "win95",
            "xp",
            "macos",
            "gnome",
            "cyberpunk",
            "paper",
            "solarized",
            "vaporwave",
            "highcontrast",
            "altimit",
        ];

        for name in toml_skins {
            let generated = super::generated::load_generated_skin(name)
                .unwrap_or_else(|| panic!("no generated skin for '{name}'"))
                .unwrap_or_else(|e| panic!("generated '{name}' failed: {e}"));
            let hw = load_builtin_raw(name)
                .unwrap_or_else(|e| panic!("handwritten '{name}' failed: {e}"));

            // Manifest name must match.
            assert_eq!(
                generated.manifest.name, hw.manifest.name,
                "name mismatch for '{name}'"
            );

            // Strings must match.
            assert_eq!(
                generated.strings.prompt_format, hw.strings.prompt_format,
                "prompt_format mismatch for '{name}'"
            );
            assert_eq!(
                generated.strings.boot_text, hw.strings.boot_text,
                "boot_text mismatch for '{name}'"
            );
            assert_eq!(
                generated.strings.title, hw.strings.title,
                "title mismatch for '{name}'"
            );

            // Theme base colors must match.
            assert_eq!(
                generated.theme.background_color(),
                hw.theme.background_color(),
                "background color mismatch for '{name}'"
            );
            assert_eq!(
                generated.theme.primary_color(),
                hw.theme.primary_color(),
                "primary color mismatch for '{name}'"
            );

            // Features must match.
            assert_eq!(
                generated.features.dashboard, hw.features.dashboard,
                "dashboard mismatch for '{name}'"
            );
            assert_eq!(
                generated.features.terminal, hw.features.terminal,
                "terminal mismatch for '{name}'"
            );
            assert_eq!(
                generated.features.window_manager, hw.features.window_manager,
                "window_manager mismatch for '{name}'"
            );
        }
    }

