// Proportional glyph metrics
// ---------------------------------------------------------------------------

/// Compute `(left_pad, advance)` for a single glyph from its bitmap data.
///
/// - `left_pad`: leftmost column containing ink (0-7).
/// - `advance`: horizontal distance to the next glyph (`ink_width + 1`, clamped to \[3, 8\]).
///
/// Space (all-zero bitmap) returns `(0, 4)`.
const fn compute_metrics(data: &[u8; 8]) -> (u8, u8) {
    let mut leftmost: u8 = 8;
    let mut rightmost: u8 = 0;
    let mut has_ink = false;

    let mut row = 0;
    while row < 8 {
        let bits = data[row];
        if bits != 0 {
            let mut col: u8 = 0;
            while col < 8 {
                if bits & (0x80 >> col) != 0 {
                    if col < leftmost {
                        leftmost = col;
                    }
                    if col > rightmost || !has_ink {
                        rightmost = col;
                    }
                    has_ink = true;
                }
                col += 1;
            }
        }
        row += 1;
    }

    if !has_ink {
        // Space or blank glyph.
        return (0, 4);
    }

    let ink_width = rightmost - leftmost + 1;
    let mut advance = ink_width + 1;
    if advance < 3 {
        advance = 3;
    }
    if advance > 8 {
        advance = 8;
    }
    (leftmost, advance)
}

/// Compute metrics for all 95 printable ASCII glyphs at compile time.
const fn compute_all_metrics() -> [(u8, u8); 95] {
    let mut table = [(0u8, 8u8); 95];
    let mut i = 0;
    while i < 95 {
        table[i] = compute_metrics(&FONT_DATA[i]);
        i += 1;
    }
    table
}

/// Pre-computed `(left_pad, advance)` for ASCII 0x20..=0x7E.
static GLYPH_METRICS: [(u8, u8); 95] = compute_all_metrics();

/// Compute metrics for all extended glyphs at compile time.
const fn compute_extended_metrics<const N: usize>(glyphs: &[(u32, [u8; 8]); N]) -> [(u8, u8); N] {
    let mut table = [(0u8, 8u8); N];
    let mut i = 0;
    while i < N {
        table[i] = compute_metrics(&glyphs[i].1);
        i += 1;
    }
    table
}

/// Pre-computed metrics for extended glyphs, same order as EXTENDED_GLYPHS.
static EXTENDED_METRICS: [(u8, u8); EXTENDED_COUNT] = {
    // SAFETY: EXTENDED_GLYPHS has exactly EXTENDED_COUNT elements.
    // We need the sized array reference for const generics, so build it here.
    let mut arr = [(0u32, [0u8; 8]); EXTENDED_COUNT];
    let mut i = 0;
    while i < EXTENDED_COUNT {
        arr[i] = EXTENDED_GLYPHS[i];
        i += 1;
    }
    compute_extended_metrics(&arr)
};

/// Return `(left_pad, advance)` for a character.
///
/// - `left_pad`: first column with ink (used to shift rendering).
/// - `advance`: horizontal pixels consumed (including 1px inter-glyph gap).
///
/// Non-printable / out-of-range characters return `(0, 8)` (full-width).
pub fn glyph_metrics(ch: char) -> (u8, u8) {
    let code = ch as u32;
    if code >= FIRST_CHAR as u32 && code <= LAST_CHAR as u32 {
        return GLYPH_METRICS[(code - FIRST_CHAR as u32) as usize];
    }
    // Binary search extended table.
    let mut lo = 0usize;
    let mut hi = EXTENDED_COUNT;
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let cp = EXTENDED_GLYPHS[mid].0;
        if cp == code {
            return EXTENDED_METRICS[mid];
        } else if cp < code {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    (0, 8)
}

/// Return the proportional advance width for a character (in pixels at scale 1).
pub fn glyph_advance(ch: char) -> u32 {
    glyph_metrics(ch).1 as u32
}

/// Return the advance width for a character at a specific font size.
///
/// Uses sub-pixel scaling: `advance * font_size / 8` (integer arithmetic,
/// rounds down). This matches the pixel widths produced by the sub-pixel
/// glyph renderer.
pub fn glyph_advance_scaled(ch: char, font_size: u16) -> u32 {
    let advance = glyph_metrics(ch).1 as u32;
    let fs = font_size.max(1) as u32;
    advance * fs / 8
}

/// Fast ASCII-only glyph metrics lookup.
///
/// For ASCII bytes (0x20..=0x7E), returns `(left_pad, advance)` directly
/// from the metrics table. For out-of-range bytes, returns the default `(0, 8)`.
///
/// This avoids the overhead of the general `glyph_metrics()` which handles
/// Unicode via binary search over extended tables.
#[inline(always)]
pub fn glyph_metrics_ascii(byte: u8) -> (u8, u8) {
    if (FIRST_CHAR..=LAST_CHAR).contains(&byte) {
        GLYPH_METRICS[(byte - FIRST_CHAR) as usize]
    } else {
        (0, 8)
    }
}

/// Iterate over the set pixels of a bitmap glyph, calling `emit` for each.
///
/// The 8x8 bitmap glyph for `ch` is iterated row-by-row, column-by-column.
/// For each set pixel, `emit(col - left_pad, row)` is called with the
/// left-pad-adjusted column and the row index (both in 0..8 range).
///
/// This extracts the common glyph iteration loop shared by SDL, UE5, and
/// WASM backends, eliminating duplicate bit-masking logic.
pub fn for_each_glyph_pixel(ch: char, mut emit: impl FnMut(i32, i32)) {
    let data = glyph(ch);
    let (left_pad, _) = glyph_metrics(ch);
    let left_pad = left_pad as i32;
    for row in 0..8i32 {
        let bits = data[row as usize];
        if bits == 0 {
            continue;
        }
        for col in 0..8i32 {
            if bits & (0x80 >> col) != 0 {
                emit(col - left_pad, row);
            }
        }
    }
}

/// Return the horizontal span for row `y` of a smooth triangle glyph
/// of dimensions `(w, h)`, or `None` for rows that fall outside the
/// triangle or characters that aren't smooth triangles.
///
/// When a backend's glyph renderer encounters ▲ / ▼ it produces a
/// chunky scaled bitmap because the 8×8 source only has six rows of
/// triangle data. This helper lets each backend opt in to drawing
/// clean triangles at the target resolution instead. The returned
/// span is inclusive on both ends: `[x0, x1]`.
///
/// The vertical inset is 1/8 of the glyph height on both sides so the
/// triangle has breathing room inside its cell — matches the original
/// 8×8 bitmap's framing.
#[inline]
pub fn smooth_triangle_span(ch: char, y: i32, w: i32, h: i32) -> Option<(i32, i32)> {
    if w < 2 || h < 4 || y < 0 || y >= h {
        return None;
    }
    let apex_top = match ch {
        '\u{25B2}' => true,  // ▲
        '\u{25BC}' => false, // ▼
        _ => return None,
    };
    let margin_y = (h / 8).max(1);
    let tri_top = margin_y;
    let tri_bot = h - margin_y;
    let tri_h = tri_bot - tri_top;
    if y < tri_top || y >= tri_bot || tri_h < 1 {
        return None;
    }
    let inner_y = y - tri_top;
    let denom = (tri_h - 1).max(1) as f32;
    let t = if apex_top {
        inner_y as f32 / denom
    } else {
        (tri_h - 1 - inner_y) as f32 / denom
    };
    // Leave one pixel of horizontal breathing room on each side.
    let inner_w = (w - 2).max(1);
    let row_w = (1.0 + t * (inner_w - 1).max(1) as f32).round() as i32;
    let row_w = row_w.clamp(1, w);
    let x0 = (w - row_w) / 2;
    let x1 = x0 + row_w - 1;
    Some((x0, x1))
}

/// Whether `ch` is a smooth-triangle codepoint (▲ or ▼). Backends check
/// this up front to choose between the bitmap and triangle rendering
/// paths without doing the `match` twice.
#[inline]
pub fn is_smooth_triangle(ch: char) -> bool {
    matches!(ch, '\u{25B2}' | '\u{25BC}')
}

